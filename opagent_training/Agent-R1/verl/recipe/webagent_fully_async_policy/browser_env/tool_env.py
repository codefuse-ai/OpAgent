# Independent step function
def step(env: 'ToolEnv', action_text: str, webloop: Any):
    """
    Execute one step of environment interaction

    Args:
        env: The tool environment
        action_text: Text generated by LLM

    Returns:
        (observation, reward, done, info)
    """
    env.steps_taken += 1
    action = env.extract_tool_call(action_text)

    if action == env.INVALID_ACTION:

        if env.extract_answer(action_text):
            reward = 0
            result = {"content": "", "image": None} 
        else:
            reward = env.PENALTY_FOR_INVALID  # Syntax error penalty
            result = {"content": "Invalid tool call format. Please use <tool_call>{\"name\": \"tool_name\", \"arguments\": {params_json}}</tool_call> format.", "image": None} # answer error penalty
        env._update_tracking_variables(
            response=action_text,
            action=action,
            action_is_valid=False,
            action_is_effective=False,
            reward=reward
        )
        return result, reward, False, {"action_is_valid": False, "action_is_effective": False}

    tool_name = action["tool"]
    tool_args = action["args"]
    # Validate if the tool exists
    if tool_name not in env.tool_map:
        result = {"content": f"Unknown tool: {tool_name}", "image": None}
        reward = env.PENALTY_FOR_INEFFECTIVE  # Semantic error penalty
        env._update_tracking_variables(
            response=action_text,
            action=action,
            action_is_valid=True,
            action_is_effective=False,
            reward=reward
        )
        return result, reward, False, {"action_is_valid": True, "action_is_effective": False}

    # Get tool instance
    tool = env.tool_map[tool_name]

    # Validate tool arguments
    try:
        is_valid, error_msg = tool.validate_args(tool_args)
    except Exception as e:
        logger.error(f"Error validating tool arguments for tool '{tool_name}': {e}")
        is_valid = False
        error_msg = str(e)

    if not is_valid:
        result = {"content": f"Invalid arguments for tool '{tool_name}': {error_msg}", "image": None}
        reward = env.PENALTY_FOR_INEFFECTIVE  # Semantic error penalty
        env._update_tracking_variables(
            response=action_text,
            action=action,
            action_is_valid=True,
            action_is_effective=False,
            reward=reward
        )
        return result, reward, False, {"action_is_valid": True, "action_is_effective": False}

    # Execute tool
    try:
        result = tool.execute(tool_args)
        reward = tool.calculate_reward(tool_args, result, env, env.PENALTY_FOR_INEFFECTIVE)

        # Record tool call history
        env.tool_history.append({
            "tool": tool_name,
            "args": tool_args,
            "result": result
        })

        # Check if max turns reached
        done = env.steps_taken >= env.max_turns

        env._update_tracking_variables(
            response=action_text,
            action=action,
            action_is_valid=True,
            action_is_effective=True,
            reward=reward
        )

        # Return the full result dictionary as observation
        if not isinstance(result, dict):
            result = {"content": str(result), "image": None}
        return result, reward, done, {"action_is_valid": True, "action_is_effective": True}
    except Exception as e:
        error_trace = traceback.format_exc()
        logger.error(f"Error executing tool '{tool_name}': {e}\nTraceback:\n{error_trace}")
        result = {"content": f"Error executing tool '{tool_name}': {str(e)}", "image": None}
        reward = env.PENALTY_FOR_INEFFECTIVE  # Runtime error penalty

        env._update_tracking_variables(
            response=action_text,
            action=action,
            action_is_valid=True,
            action_is_effective=False,
            reward=reward
        )

        return result, reward, False, {"action_is_valid": True, "action_is_effective": False}

# Batch step function
def step_batch(envs: List['ToolEnv'], action_texts: List[str]):
    """
    Execute batch steps of environment interaction

    Args:
        envs: List of tool environments
        action_texts: List of texts generated by LLM

    Returns:
        List of (observation, reward, done, info) tuples
    """
    assert len(envs) == len(action_texts), "Number of environments and actions must match"

    # Group actions by tool name and environment
    tool_groups = {}
    tool_indices = {}
    env_indices = {}
    raw_prediction_indices = {}
    action_map = {}
    results = [None] * len(envs)

    # First pass: extract tool calls and group by tool name
    for i, (env, action_text) in enumerate(zip(envs, action_texts)):
        # Extract the tool call
        action = env.extract_tool_call(action_text)
        action_map[i] = (env, action, action_text)

        # Handle invalid actions
        if action == env.INVALID_ACTION:
            result = {"content": "Invalid tool call format. Please use <tool_call>{\"name\": \"tool_name\", \"arguments\": {params_json}}</tool_call> format.", "image": None}
            env.steps_taken += 1
            env._update_tracking_variables(
                response=action_text,
                action=action,
                action_is_valid=False,
                action_is_effective=False,
                reward=env.PENALTY_FOR_INVALID  # Syntax error penalty
            )
            results[i] = (result, env.PENALTY_FOR_INVALID, False, {"action_is_valid": False, "action_is_effective": False})
            continue

        tool_name = action["tool"]
        tool_args = action["args"]

        if not isinstance(tool_name, str):
            result = {"content": f"Invalid tool name: {tool_name}", "image": None}
            env.steps_taken += 1
            env._update_tracking_variables(
                response=action_text,
                action=action,
                action_is_valid=True,
                action_is_effective=False,
                reward=env.PENALTY_FOR_INEFFECTIVE  # Semantic error penalty
            )
            results[i] = (result, env.PENALTY_FOR_INEFFECTIVE, False, {"action_is_valid": True, "action_is_effective": False})
            logger.warning(f"Invalid tool name: '{tool_name}' in action: {action_text} end-------")
            continue

        # Handle unknown tools
        if tool_name not in env.tool_map:
            result = {"content": f"Unknown tool: {tool_name}", "image": None}
            env.steps_taken += 1
            env._update_tracking_variables(
                response=action_text,
                action=action,
                action_is_valid=True,
                action_is_effective=False,
                reward=env.PENALTY_FOR_INEFFECTIVE  # Semantic error penalty
            )
            results[i] = (result, env.PENALTY_FOR_INEFFECTIVE, False, {"action_is_valid": True, "action_is_effective": False})
            logger.warning(f"Unknown tool: '{tool_name}' in action: {action_text} end-------")
            continue

        # Get tool instance
        tool = env.tool_map[tool_name]

        # Validate tool arguments
        try:
            is_valid, error_msg = tool.validate_args(tool_args)
        except Exception as e:
            logger.error(f"Error validating tool arguments for tool '{tool_name}': {e}")
            is_valid = False
            error_msg = str(e)

        if not is_valid:
            result = {"content": f"Invalid arguments for tool '{tool_name}': {error_msg}", "image": None}
            env.steps_taken += 1
            env._update_tracking_variables(
                response=action_text,
                action=action,
                action_is_valid=True,
                action_is_effective=False,
                reward=env.PENALTY_FOR_INEFFECTIVE  # Semantic error penalty
            )
            results[i] = (result, env.PENALTY_FOR_INEFFECTIVE, False, {"action_is_valid": True, "action_is_effective": False})
            logger.warning(f"Invalid arguments for tool: {error_msg} end-------")
            continue

        # Group by tool name
        if tool_name not in tool_groups:
            tool_groups[tool_name] = []
            tool_indices[tool_name] = []
            env_indices[tool_name] = []
            raw_prediction_indices[tool_name] = []

        tool_groups[tool_name].append(tool_args)
        tool_indices[tool_name].append(i)
        env_indices[tool_name].append(env)
        raw_prediction_indices[tool_name].append(action_text)

    # Second pass: execute tools in batch where possible
    for tool_name, args_list in tool_groups.items():
        indices = tool_indices[tool_name]
        envs_list = env_indices[tool_name]

        # All environments share the same tool instances, so we can use the first one
        tool = envs_list[0].tool_map[tool_name]
        raw_prediction_list = raw_prediction_indices[tool_name]
        try:
            # Try batch execution
            if isinstance(tool, WebBrowserTool):
                batch_results = tool.batch_execute(args_list, envs_list, raw_prediction_list)
            else:
                batch_results = tool.batch_execute(args_list)
            
            logger.debug(f"Batch execution results for tool '{tool_name}': {batch_results}")

            # --- 第 1 步：并发提交 `calculate_reward` 任务 ---
            future_to_idx = {}
            for idx_i, (env, result, args) in enumerate(zip(envs_list, batch_results, args_list)):
                # 提交 calculate_reward 函数作为任务
                future = env.owner_actor.submit(
                    tool.calculate_reward, 
                    args, 
                    result, 
                    env, 
                    env.PENALTY_FOR_INEFFECTIVE
                )
                future_to_idx[future] = idx_i

            # --- 第 2 步：异步收集所有计算好的 reward ---
            # 使用一个字典来存储 idx -> reward 的映射，确保顺序正确
            
            calculated_rewards = [None] * len(envs_list)
            for future in concurrent.futures.as_completed(future_to_idx):
                idx_i = future_to_idx[future]
                env = envs_list[idx_i] # 获取对应的env，主要用于异常处理时的penalty
                
                try:
                    # 获取计算结果
                    reward = future.result()
                    calculated_rewards[idx_i] = reward
                except Exception as exc:
                    # 如果 calculate_reward 内部发生异常，记录日志并使用惩罚值
                    logger.error(f"ERROR: Reward calculation for batch item index {idx_i} failed: {exc}. Using penalty.")
                    calculated_rewards[idx_i] = env.PENALTY_FOR_INEFFECTIVE

            # --- 第 3 步：使用预先计算好的 reward，完成剩余的串行处理 ---
            # 原始循环，但现在不再调用 calculate_reward
            for idx, reward, env, result, args in zip(indices, calculated_rewards, envs_list, batch_results, args_list):
                env.steps_taken += 1

                # 记录工具调用历史
                env.tool_history.append({
                    "tool": tool_name,
                    "args": args,
                    "result": result
                })

                # 检查是否达到最大回合数
                done = env.steps_taken >= env.max_turns

                # 更新追踪变量
                action_text = action_texts[idx]
                action = action_map[idx][1]
                env._update_tracking_variables(
                    response=action_text,
                    action=action,
                    action_is_valid=True,
                    action_is_effective=True,
                    reward=reward
                )

                # 返回完整的结果字典作为观察值
                if not isinstance(result, dict):
                    result = {"content": str(result), "image": None}
                # 将最终结果存入正确的位置
                results[idx] = (result, reward, done, {"action_is_valid": True, "action_is_effective": True})
        
        except Exception as e:
            logger.error(f"Error during batch execution of tool '{tool_name}': {e}", exc_info=True)
            # Handle batch execution failure for all related environments
            for idx in indices:
                env = envs[idx]
                action_text = action_texts[idx]
                action = action_map[idx][1]
                result = {"content": f"Batch execution error for tool '{tool_name}': {str(e)}", "image": None}
                reward = env.PENALTY_FOR_INEFFECTIVE
                
                env.steps_taken += 1
                env._update_tracking_variables(
                    response=action_text,
                    action=action,
                    action_is_valid=True,
                    action_is_effective=False,
                    reward=reward
                )
                results[idx] = (result, reward, False, {"action_is_valid": True, "action_is_effective": False})
    
    return results

class ToolEnv:
    """
    Generic tool environment class, handling tool calls, history tracking, and state
    """
    INVALID_ACTION = {"tool": "invalid", "args": {}}
    PENALTY_FOR_INVALID = -0.05
    PENALTY_FOR_INEFFECTIVE = -0.01
    
    def __init__(self, tools: List[WebBrowserTool] = None, max_turns: int = 10):
        self.tools = tools or []
        self.tool_map = {tool.name: tool for tool in self.tools}
        self.tool_desc = [tool.get_description() for tool in self.tools]
        self.max_turns = max_turns
        self.reset_tracking_variables()

    def tools_format_func(self) -> str:
        template = """# Tools

Based on the web screen shot and content, you need call a function to help you fulfill the user's query.

You are provided with function signatures within <tools></tools> XML tags:
<tools>
{tools}
</tools>

For each function call, return a json object with function name and arguments within <tool_call></tool_call> XML tags:
<tool_call>
{{"name": <function-name>, "arguments": <args-json-object>}}
</tool_call>"""
        tools = "\n".join([f"{json.dumps(tool.get_description(), ensure_ascii=False)}" for tool in self.tools])
        return template.format(tools=tools)
        
    def reset_tracking_variables(self):
        self.rewards = []
        self.tool_history = []
        self.steps_taken = 0
        self._actions = []
        self._actions_valid = []
        self._actions_effective = []
    
    def get_tracking_variables(self) -> Dict:
        return {
            "rewards": self.rewards,
            "total_reward": sum(self.rewards),
            "steps_taken": self.steps_taken,
            "tool_history": self.tool_history,
            "actions": self._actions,
            "actions_valid": self._actions_valid,
            "actions_effective": self._actions_effective,
        }
    
    def _update_tracking_variables(
            self, 
            response: str,
            action: Any, 
            action_is_valid: bool,
            action_is_effective: bool,
            reward: float,
        ):
        self._actions.append(response)
        if action_is_valid:
            self._actions_valid.append(action)
        else:
            self._actions_valid.append(None)
        if action_is_effective:
            self._actions_effective.append(action)
        else:
            self._actions_effective.append(None)
        
        self.rewards.append(reward)
    
    def adjust_action_string(self,
        gpt_response_string: str, 
        grid_thw: list, 
        image_token_num: int, 
        image_file_list: list
    ) -> str:
        pattern = r'<tool_call>(.*?)</tool_call>'

        def replacer(match):
            json_content = match.group(1)

            try:
                action_data = json.loads(json_content)
            except json.JSONDecodeError:
                return match.group(0)

            if "arguments" not in action_data:
                return match.group(0)

            args = action_data["arguments"]
            action_name = action_data.get("name")
            
            coord_keys = ["coords", "from_coord", "to_coord"]
            needs_scaling = (
                any(key in args for key in coord_keys) or
                (action_name in ["scroll", "hscroll"] and "distance" in args)
            )

            if not needs_scaling:
                return match.group(0)

            idx = image_token_num - 1
            try:
                original_w, original_h = imagesize.get(image_file_list[idx])
            except (FileNotFoundError, IndexError, TypeError):
                return match.group(0)

            if original_w == 0 or original_h == 0:
                return match.group(0)

            resize_h = grid_thw[idx][1] * 14
            resize_w = grid_thw[idx][2] * 14

            def scale_coords(coords_list):
                if not isinstance(coords_list, list) or len(coords_list) != 2:
                    return coords_list
                rel_x, rel_y = coords_list
                abs_x = int(rel_x / original_w * resize_w)
                abs_y = int(rel_y / original_h * resize_h)
                return [abs_x, abs_y]

            for key in coord_keys:
                if key in args:
                    args[key] = scale_coords(args[key])

            if "distance" in args:
                rel_distance = args["distance"]
                if action_name == "scroll":
                    args["distance"] = int(rel_distance / original_h * resize_h)
                elif action_name == "hscroll":
                    args["distance"] = int(rel_distance / original_w * resize_w)
            
            updated_json_content = json.dumps(action_data, separators=(',', ':'))
            return f"<tool_call>{updated_json_content}</tool_call>"

        return re.sub(pattern, replacer, gpt_response_string, flags=re.DOTALL)

    def extract_answer(self, text: str):
        answer_pattern = r'<answer>(.*?)</answer>'
        answer_match = re.search(answer_pattern, text, re.DOTALL)
        if answer_match:
            return True
        else:
            return False
        

    def extract_tool_call(self, text: str) -> Dict:
        tool_call_pattern = r'<tool_call>(.*?)</tool_call>'
        tool_call_match = re.search(tool_call_pattern, text, re.DOTALL)
        
        if not tool_call_match:
            return self.INVALID_ACTION
        tool_call_json = ""
        try:
            tool_call_json = tool_call_match.group(1).strip()
            logger.debug(f"Extracted tool call JSON: {tool_call_json}")
            tool_call_data = json_repair.loads(tool_call_json)
            
            if "name" not in tool_call_data:
                return self.INVALID_ACTION
                
            tool_name = tool_call_data["name"]
            tool_args = tool_call_data.get("arguments", {})
            
            return {"tool": tool_name, "args": tool_args}
        except json.JSONDecodeError:
            logger.warning(f"Action JSONDecodeError for content: {tool_call_json}")
            return self.INVALID_ACTION
        except Exception:
            logger.error("An unexpected error occurred during action extraction.", exc_info=True)
            return self.INVALID_ACTION
    
    def get_tool_history_context(self) -> str:
        if not self.tool_history:
            return "No tool call history yet."
        
        context = "Tool call history:\n"
        for i, call in enumerate(self.tool_history):
            context += f"{i+1}. Tool: {call['tool']}\n"
            context += f"   Arguments: {json.dumps(call['args'], ensure_ascii=False)}\n"
            result = call['result']
            if isinstance(result, dict):
                content = result.get('content', '')
                # Truncate long content for brevity in history
                if len(content) > 200:
                    content = content[:200] + "..."
                context += f"   Result: {content}\n"
            else:
                str_result = str(result)
                if len(str_result) > 200:
                    str_result = str_result[:200] + "..."
                context += f"   Result: {str_result}\n"
            context += "\n"
        
        return context
    
    def get_available_tools_description(self) -> str:
        if not self.tools:
            return "No tools available."
            
        descriptions = ["Available tools:"]
        for tool in self.tools:
            descriptions.append(tool.get_simple_description())
            
        return "\n\n".join(descriptions)
    
    def copy(self):
        env = ToolEnv(tools=self.tools, max_turns=self.max_turns)
        env.tool_history = deepcopy(self.tool_history)
        env.rewards = deepcopy(self.rewards)
        env.steps_taken = self.steps_taken
        env._actions = deepcopy(self._actions)
        env._actions_valid = deepcopy(self._actions_valid)
        env._actions_effective = deepcopy(self._actions_effective)
        return env

def get_integer_after_prefix(text: str, prefix: str) -> int | None:
    """
    使用正则表达式从字符串中提取指定前缀后的整数。

    :param text: 原始字符串。
    :param prefix: 要查找的前缀。
    :return: 提取到的整数，如果未找到则返回 None。
    """
    # re.escape(prefix) 可以防止前缀中的特殊字符影响正则表达式
    pattern = re.compile(re.escape(prefix) + r"(\d+)")
    match = pattern.search(text)
    
    if match:
        return int(match.group(1))
    
    return None


