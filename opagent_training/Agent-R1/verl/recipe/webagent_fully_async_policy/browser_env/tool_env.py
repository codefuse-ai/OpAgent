    """测试 WebBrowserTool 的 convert_action_to_string_coords 函数"""
    print("\n" + "="*60)
    print("测试 WebBrowserTool 的动作转换")
    print("="*60 + "\n")
    
    # 创建一个模拟的环境对象
    class MockEnv:
        def __init__(self):
            self.viewport_size = {'width': 1000, 'height': 1000}
    
    mock_env = MockEnv()
    
    # 测试 1: find 动作转换
    print("测试 1: find 动作转换")
    print("-" * 40)
    tool = WebBrowserTool(name="find")
    properties = {"search_term": "测试文本"}
    result = tool.convert_action_to_string_coords(properties, mock_env)
    print(f"输入: {properties}")
    print(f"输出: {result}")
    assert result == "find [测试文本]", f"转换错误，期望 'find [测试文本]'，实际 '{result}'"
    print("✓ find 动作转换测试通过\n")
    
    # 测试 2: get_file 动作转换（带坐标反缩放）
    print("测试 2: get_file 动作转换")
    print("-" * 40)
    tool = WebBrowserTool(name="get_file")
    properties = {"coords": [500, 600]}  # 在 1000x1000 的 resized 空间中
    result = tool.convert_action_to_string_coords(properties, mock_env)
    print(f"输入: {properties}")
    print(f"输出: {result}")
    # 坐标应该从 resized 空间转换回原始空间：(500/1000)*1000 = 500
    assert "get_file" in result, f"转换结果应包含 'get_file'"
    print("✓ get_file 动作转换测试通过\n")
    
    # 测试 3: scroll 动作转换（四个方向）
    print("测试 3: scroll 动作转换（四个方向）")
    print("-" * 40)
    tool = WebBrowserTool(name="scroll")
    for direction in ["up", "down", "left", "right"]:
        properties = {"direction": direction, "distance": 500}
        result = tool.convert_action_to_string_coords(properties, mock_env)
        print(f"输入: {properties}")
        print(f"输出: {result}")
        assert f"scroll [{direction}]" in result, f"转换结果应包含 'scroll [{direction}]'"
        assert "[500]" in result, f"转换结果应包含距离 [500]"
    print("✓ scroll 四个方向转换测试通过\n")
    
    # 测试 4: scroll 带坐标的动作转换
    print("测试 4: scroll 带坐标的动作转换")
    print("-" * 40)
    tool = WebBrowserTool(name="scroll")
